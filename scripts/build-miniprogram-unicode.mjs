import {readFile, writeFile} from 'node:fs/promises';

if (process.versions.unicode !== '17.0') throw new Error('Regenerate with a Node runtime using Unicode 17.0 (validated with Node 24.19.0)');

// Property escapes are supported by the build-time Node engine, but not by
// every Android WeChat engine. Ship numeric ranges instead of this regex.
const ranges = [];
for (let code = 0; code <= 0x10ffff; code++) {
  if (!/\p{M}/u.test(String.fromCodePoint(code))) continue;
  if (ranges.length && ranges[ranges.length - 1] === code - 1) ranges[ranges.length - 1] = code;
  else ranges.push(code, code);
}
const rows = [];
for (let i = 0; i < ranges.length; i += 12) {
  rows.push(`  ${ranges.slice(i, i + 12).map(n => `0x${n.toString(16)}`).join(', ')},`);
}
const file = new URL('../miniprogram/miniprogram/core/search.ts', import.meta.url);
const source = await readFile(file, 'utf8');
const section = /\/\/ BEGIN GENERATED UNICODE MARKS\n[\s\S]*?\/\/ END GENERATED UNICODE MARKS/;
if (!section.test(source)) throw new Error('Unicode table markers are missing');
await writeFile(file, source.replace(section,
  `// BEGIN GENERATED UNICODE MARKS\n// Unicode ${process.versions.unicode} General_Category=Mark (Mn, Mc, Me).\n`
  + '// Generated by scripts/build-miniprogram-unicode.mjs; pairs are inclusive.\n'
  + '// Numeric data keeps Android runtime parsing independent of Unicode regex support.\n'
  + `const markRanges: readonly number[] = [\n${rows.join('\n')}\n];\n// END GENERATED UNICODE MARKS`));
