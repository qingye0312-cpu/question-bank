import {readFile, writeFile, mkdir} from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const version = JSON.parse(await readFile(new URL('package.json',root),'utf8')).version;
const prompt = await readFile(new URL('templates/大模型拍照识题_单题输出提示词_v1_草案.txt',root),'utf8');
const generated = `// Generated by scripts/sync-client-assets.mjs; edit the canonical template instead.\nexport const APP_VERSION = ${JSON.stringify(version)};\nexport const MODEL_PROMPT = ${JSON.stringify(prompt)};\n`;
const files = new Map([
  ['miniprogram/miniprogram/core/sync.ts', '// Generated from shared/sync.ts.\n'+(await readFile(new URL('shared/sync.ts',root),'utf8')).replace("'./intake.ts'","'./intake'")],
  ['src/generated/client-assets.ts', generated],
  ['miniprogram/miniprogram/generated/client-assets.ts', generated],
  ['miniprogram/miniprogram/core/intake.ts', '// Generated from shared/intake.ts.\n'+await readFile(new URL('shared/intake.ts',root),'utf8')],
]);
for (const [path, content] of files) {
  const url = new URL(path,root);
  if (process.argv.includes('--check')) {
    if (await readFile(url,'utf8').catch(()=>null) !== content) throw new Error(`${path} 需要同步：node scripts/sync-client-assets.mjs`);
  } else { await mkdir(new URL('.',url),{recursive:true}); await writeFile(url,content); }
}
